CREATE TABLE categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    sort_order INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE menus (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT NOT NULL,
    name VARCHAR(255) NOT NULL,
    description TEXT,
    image_url VARCHAR(255),
    base_price INTEGER NOT NULL,
    cook_time_sec INTEGER NOT NULL,
    status VARCHAR(20) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_menus_category FOREIGN KEY (category_id) REFERENCES categories (id),
    CONSTRAINT ck_menus_base_price CHECK (base_price >= 0),
    CONSTRAINT ck_menus_cook_time_sec CHECK (cook_time_sec >= 0),
    CONSTRAINT ck_menus_status CHECK (status IN ('ON_SALE', 'PAUSED', 'HIDDEN'))
);

CREATE TABLE menu_options (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    menu_id BIGINT NOT NULL,
    name VARCHAR(255) NOT NULL,
    extra_price INTEGER NOT NULL,
    extra_cook_time_sec INTEGER NOT NULL,
    is_default BOOLEAN NOT NULL DEFAULT FALSE,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_menu_options_menu FOREIGN KEY (menu_id) REFERENCES menus (id),
    CONSTRAINT ck_menu_options_extra_price CHECK (extra_price >= 0),
    CONSTRAINT ck_menu_options_extra_cook_time_sec CHECK (extra_cook_time_sec >= 0)
);

CREATE INDEX idx_menus_category_id ON menus (category_id);
CREATE INDEX idx_menu_options_menu_id ON menu_options (menu_id);
