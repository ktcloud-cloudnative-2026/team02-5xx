CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(254) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    nickname VARCHAR(50),
    name VARCHAR(100),
    phone VARCHAR(32),
    role VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT ck_users_role CHECK (role IN ('CUSTOMER', 'STORE_ADMIN')),
    CONSTRAINT ck_users_status CHECK (status IN ('ACTIVE', 'SUSPENDED', 'WITHDRAWN'))
);

CREATE TABLE user_agreements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users (id),
    type VARCHAR(20) NOT NULL,
    version VARCHAR(64) NOT NULL,
    agreed BOOLEAN NOT NULL,
    agreed_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_user_agreements_user_type_version UNIQUE (user_id, type, version),
    CONSTRAINT ck_user_agreements_type CHECK (type IN ('TERMS', 'PRIVACY'))
);
