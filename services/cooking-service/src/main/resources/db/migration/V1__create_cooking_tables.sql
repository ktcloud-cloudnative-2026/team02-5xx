-- Cooking 서비스 초기 스키마
-- 기준: Notion ERD "3-6. 조리 (cooking_svc)"
-- 포함: cooking_tickets, cooking_ticket_items, outbox_events, processed_events, congestion_thresholds
--       (outbox_events · processed_events는 API 명세 처리 규칙 "이벤트 중복 방지" 기준)
-- 제외: congestion_snapshots (이력용 선택 표, 필요 시 이후 버전으로 추가)

-- 조리 전표: OrderConfirmed 이벤트 1건당 1행
CREATE TABLE cooking_tickets (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id            BIGINT       NOT NULL,                    -- Order 서비스의 주문 ID (FK 없음)
    order_no            VARCHAR(30)  NOT NULL,                    -- 화면 표시용 주문번호 (복사)
    status              VARCHAR(20)  NOT NULL,
    estimated_cook_sec  INTEGER      NOT NULL,                    -- 예상 조리 시간 합(초)
    queued_at           TIMESTAMPTZ  NOT NULL DEFAULT now(),      -- Cooking DB 실제 등록 시각 (FIFO 기준)
    started_at          TIMESTAMPTZ,
    completed_at        TIMESTAMPTZ,
    canceled_at         TIMESTAMPTZ,
    CONSTRAINT uk_cooking_tickets_order_id UNIQUE (order_id),
    CONSTRAINT ck_cooking_tickets_status
        CHECK (status IN ('WAITING', 'COOKING', 'DONE', 'CANCELED')),
    CONSTRAINT ck_cooking_tickets_estimated_cook_sec CHECK (estimated_cook_sec >= 0)
);

-- 상태별 FIFO 조회 (예: WAITING을 queued_at 순으로)
CREATE INDEX idx_cooking_tickets_status_queued_at
    ON cooking_tickets (status, queued_at, id);

-- 조리 항목: 전표에 포함된 메뉴별 행
CREATE TABLE cooking_ticket_items (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id       BIGINT        NOT NULL,
    menu_id         BIGINT        NOT NULL,                       -- Menu 서비스의 메뉴 ID (FK 없음)
    menu_name       VARCHAR(100)  NOT NULL,                       -- 메뉴 이름 (복사)
    option_summary  VARCHAR(255),                                 -- 옵션 요약 (예: 세트)
    quantity        INTEGER       NOT NULL,
    cook_time_sec   INTEGER       NOT NULL,                       -- 1개 조리 시간 (복사)
    CONSTRAINT fk_cooking_ticket_items_ticket
        FOREIGN KEY (ticket_id) REFERENCES cooking_tickets (id),
    CONSTRAINT ck_cooking_ticket_items_quantity CHECK (quantity > 0),
    CONSTRAINT ck_cooking_ticket_items_cook_time_sec CHECK (cook_time_sec >= 0)
);

CREATE INDEX idx_cooking_ticket_items_ticket_id
    ON cooking_ticket_items (ticket_id);

-- 발행 이벤트 아웃박스 (CookingCompleted 등): 상태 변경과 같은 트랜잭션에 저장 후 별도로 발행
-- 구조는 Order 서비스 outbox_events와 동일하게 맞춤
CREATE TABLE outbox_events (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id    UUID         NOT NULL UNIQUE,
    event_type  VARCHAR(50)  NOT NULL,
    payload     JSONB        NOT NULL,
    status      VARCHAR(20)  NOT NULL DEFAULT 'PENDING',
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    sent_at     TIMESTAMPTZ,
    CONSTRAINT ck_outbox_events_status CHECK (status IN ('PENDING', 'SENT'))
);

CREATE INDEX idx_outbox_events_pending
    ON outbox_events (created_at) WHERE status = 'PENDING';

-- 수신 이벤트 중복 처리 방지 (메시지의 eventId 저장)
CREATE TABLE processed_events (
    event_id      UUID          PRIMARY KEY,
    event_type    VARCHAR(100)  NOT NULL,                         -- 예: OrderConfirmed
    processed_at  TIMESTAMPTZ   NOT NULL DEFAULT now()
);

-- 혼잡 판단 기준값
CREATE TABLE congestion_thresholds (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    busy_wait_sec  INTEGER      NOT NULL,                         -- 예상 대기 시간이 이 값 이상이면 혼잡(초)
    updated_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_congestion_thresholds_busy_wait_sec CHECK (busy_wait_sec > 0)
);
